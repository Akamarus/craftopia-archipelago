using System;
using CraftopiaArchipelago;
class Program {
 static void Assert(bool value,string name) { if(!value) throw new Exception(name); }
 static void Main() {
  var d=new PlayerStatusDisplay(null,_=>throw new Exception("logger unavailable"));
  try { d.ShowBlockedAction("Requires Tamer"); } catch { throw new Exception("Blocked notice must contain logger exceptions"); }
  d=new PlayerStatusDisplay(null,null);
  var show=typeof(PlayerStatusDisplay).GetMethod("Notify");
  Assert(show!=null,"Missing transient notification queue");
  show.Invoke(d,new object[]{"check:1","Check queued: <b>Axe</b>",10d});
  show.Invoke(d,new object[]{"check:1","Duplicate",11d});
  var read=typeof(PlayerStatusDisplay).GetMethod("VisibleMessages");
  string result=(string)read.Invoke(d,new object[]{11d});
  Assert(result.Contains("Check queued") && !result.Contains("Duplicate") && !result.Contains("<b>"),"dedup and plain text");
  Assert((string)read.Invoke(d,new object[]{30d})=="","messages expire");
  for(int i=0;i<100;i++) show.Invoke(d,new object[]{"burst"+i,"Message"+i,40d});
  Assert(((string)read.Invoke(d,new object[]{41d})).Split('\n',StringSplitOptions.RemoveEmptyEntries).Length<=3,"bounded visible messages");
  var context=typeof(PlayerStatusDisplay).GetMethod("SetRecipeNotice");
  Assert(context!=null,"selected recipe explanation must not depend on a craft click");
  context.Invoke(d,new object[]{"Requires Shield tier 1"});
  Assert(d.GetType().GetProperty("RecipeNotice").GetValue(d).ToString().Contains("Shield"),"selected locked recipe reason");
  context.Invoke(d,new object[]{null});
  Assert(d.GetType().GetProperty("RecipeNotice").GetValue(d).ToString()=="","clear on allowed selection or menu close");
  var clamp=typeof(PlayerStatusDisplay).GetMethod("ClampHudPosition");
  Assert(clamp!=null,"HUD position must stay on screen");
  Assert((float)clamp.Invoke(null,new object[]{-5f,1000f,340f})==0f,"left edge clamp");
  Assert((float)clamp.Invoke(null,new object[]{900f,1000f,340f})==660f,"right edge clamp");
  Assert((float)clamp.Invoke(null,new object[]{float.NaN,1000f,340f})==0f,"invalid config safe");
  Assert((float)clamp.Invoke(null,new object[]{100f,200f,340f})==0f,"small screen safe");
  var dragType=typeof(PlayerStatusDisplay).Assembly.GetType("CraftopiaArchipelago.HudDragState");
  Assert(dragType!=null,"frame-based drag state exists");
  dynamic drag=Activator.CreateInstance(dragType);
  Assert(!drag.Step(true,true,false,15f,25f,10f,20f,340f,26f,1000f,800f,200f),"press is not a save");
  Assert(drag.Active,"press inside heading captures drag");
  drag.Step(false,true,false,105f,125f,10f,20f,340f,26f,1000f,800f,200f);
  Assert(drag.X==100f && drag.Y==120f,"held pointer moves with grab offset");
  Assert(drag.Step(false,false,true,105f,125f,10f,20f,340f,26f,1000f,800f,200f),"release requests one save");
  Assert(!drag.Active,"release ends drag");
  Assert(!drag.Step(false,false,false,105f,125f,100f,120f,340f,26f,1000f,800f,200f),"idle never saves");
  drag.Step(true,true,false,50f,200f,10f,20f,340f,26f,1000f,800f,200f);
  Assert(!drag.Active,"click outside heading ignored");
  drag.Step(true,true,false,15f,25f,10f,20f,340f,26f,1000f,800f,200f);
  drag.Step(false,true,false,5000f,-100f,10f,20f,340f,26f,1000f,800f,200f);
  Assert(drag.X==660f && drag.Y==0f,"drag stays on screen");
  drag.Cancel(); Assert(!drag.Active,"hide or lost focus cancels drag");
  var activity=typeof(PlayerStatusDisplay).GetMethod("SetActivity");
  Assert(activity!=null,"activity snapshots supported");
  activity.Invoke(d,new object[]{new object[]{"<b>Skill Point</b>","Tamer","Magic","overflow"},new object[]{"Make Axe"},11L,true});
  string history=d.GetType().GetProperty("ActivityText").GetValue(d).ToString();
  Assert(history.Contains("Goal complete") && history.Contains("Items from Archipelago") && !history.Contains("Completed checks"),"clear history labels and victory");
  Assert(history.Contains("overflow") && !history.Contains("<b>"),"scrollable history retains more than three entries as plain text");
  d.TotalChecks=564;
  activity.Invoke(d,new object[]{null,new object[]{"Hidden check"},5L,false});
  Assert(d.ActivityText.Contains("5/564") && !d.ActivityText.Contains("Hidden check"),"total without individual check list");
  activity.Invoke(d,new object[]{null,null,0L,false});
  Assert(!d.GetType().GetProperty("ActivityText").GetValue(d).ToString().Contains("Make Axe"),"snapshot replaces previous session content");
  var rows=typeof(PlayerStatusDisplay).GetProperty("ReceivedItems");
  Assert(rows!=null,"Field Guide needs separate received rows");
  d.TotalChecks=50;
  d.SetActivity(new object[]{"Sword tier 3", "<b>Soul Orb</b>"},null,39,true);
  var items=(System.Collections.Generic.IReadOnlyList<string>)rows.GetValue(d);
  Assert(items.Count==2 && items[0]=="Sword tier 3" && !items[1].Contains("<"),"received rows are ordered and sanitized");
  Assert((long)typeof(PlayerStatusDisplay).GetProperty("CheckedCount").GetValue(d)==39,"separate completed count");
  Assert((bool)typeof(PlayerStatusDisplay).GetProperty("GoalComplete").GetValue(d),"goal state exposed");
  d.ClearActivity();
  Assert(((System.Collections.Generic.IReadOnlyList<string>)rows.GetValue(d)).Count==0,"session reset clears rows");
  Assert(!(bool)typeof(PlayerStatusDisplay).GetProperty("GoalComplete").GetValue(d),"session reset clears victory");
  var permissions=new PermissionManager(null,null);
  permissions.UnlockEquipmentTier("Sword",3);
  permissions.UnlockProduction("Production: smelting");
  permissions.UnlockSkillTree("Skill Tree: Tamer");
  var guide=permissions.GetGuideRows();
  Assert(guide.Contains("Sword|Tier 3") && guide.Contains("Bow|Locked"),"guide reflects exact equipment permissions");
  Assert(guide.Contains("Smelting|Unlocked") && guide.Contains("Cooking|Locked"),"guide reflects production groups");
  Assert(guide.Contains("Tamer skills|Unlocked") && guide.Contains("Combat skills 1|Unlocked") && guide.Contains("Combat skills 2|Locked"),"guide reflects starter and received skill permissions");
  permissions.Clear();
  Assert(permissions.GetGuideRows().Contains("Sword|Locked"),"guide does not retain permissions after suspension");
  Console.WriteLine("Notification tests PASS");
 }
}
